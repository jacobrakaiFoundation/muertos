"""Render rhel7_cves.json as a ranked Markdown backlog.

Usage: python3 survey/report.py <in_json> <out_md>
"""

import json
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

SEVERITIES: tuple[str, ...] = ("Critical", "Important", "Moderate", "Low")
NOT_AFFECTED = "Not affected"


@dataclass(frozen=True)
class Row:
    cve: str
    package: str
    severity: str
    cvss3: float | None
    public_date: str
    rhel7_state: str
    summary: str


def load_rows(path: Path) -> list[Row]:
    raw = json.loads(path.read_text())
    if not isinstance(raw, list):
        raise ValueError(f"{path} must hold a list, got {type(raw).__name__}")
    rows = {(r["cve"], r["package"]): Row(**r) for r in raw}
    return [r for r in rows.values() if r.rhel7_state != NOT_AFFECTED]


def severity_rank(row: Row) -> tuple[int, float]:
    rank = SEVERITIES.index(row.severity) if row.severity in SEVERITIES else len(SEVERITIES)
    return rank, -(row.cvss3 or 0.0)


def package_table(rows: list[Row]) -> list[str]:
    counts = Counter((r.package, r.severity) for r in rows)
    packages = sorted({r.package for r in rows},
                      key=lambda p: tuple(-counts[(p, s)] for s in SEVERITIES))
    lines = ["| Package | Crit | Imp | Mod | Low |", "|---|---|---|---|---|"]
    lines += [f"| {p} | " + " | ".join(str(counts[(p, s)]) for s in SEVERITIES) + " |"
              for p in packages]
    return lines


def backlog_table(rows: list[Row]) -> list[str]:
    urgent = sorted((r for r in rows if r.severity in SEVERITIES[:2]), key=severity_rank)
    lines = ["| CVE | Package | Sev | CVSS | RHEL 7 state | Summary |",
             "|---|---|---|---|---|---|"]
    lines += [f"| {r.cve} | {r.package} | {r.severity} | {r.cvss3 or ''} | {r.rhel7_state} "
              f"| {r.summary.replace('|', '/')} |" for r in urgent]
    return lines


def main(in_json: Path, out_md: Path) -> None:
    rows = load_rows(in_json)
    states = Counter(r.rhel7_state.split(" (")[0] for r in rows)
    lines = [
        "# Post-EOL CVEs affecting el7",
        "",
        f"Generated by `survey/rhel7_cves.py` + `survey/report.py` from the Red Hat Security "
        f"Data API. {len(rows)} package/CVE pairs published after 2024-06-30 are marked as "
        f"affecting RHEL 7. Kernel counts cover Important and Critical only.",
        "",
        "RHEL 7 states: " + ", ".join(f"{s} {n}" for s, n in states.most_common()) + ".",
        "\"Fixed in ELS\" means Red Hat shipped a fix to paying RHEL 7 ELS customers, which "
        "confirms el7 is affected. The patched source is not public.",
        "",
        "## By package",
        "",
        *package_table(rows),
        "",
        "## Critical and Important backlog",
        "",
        *backlog_table(rows),
        "",
    ]
    out_md.write_text("\n".join(lines))


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
